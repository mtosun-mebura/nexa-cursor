<p>
    <strong>E-mailcommunicatie</strong> toont alle mails die naar uw klanten zijn gestuurd:
    welkomstmail, boekingsbevestiging, rit geaccepteerd, factuur en herinneringen.
    U opent de inhoud en kunt een bericht opnieuw versturen.
</p>

