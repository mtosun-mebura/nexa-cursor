<div class="handleiding-tip">
    <strong class="text-foreground">Module:</strong> GPS-trackers zit niet standaard in Start, Pro of Business.
    Activeer de aanvullende module bij het abonnement (+ extra per maand). Daarna verschijnt <strong>GPS-tracker</strong> in het menu.
</div>

<div class="handleiding-step">
    <span class="handleiding-step-num">1</span>
    <div>Open <strong>GPS-tracker</strong> → <strong>Voertuigen</strong> om de live kaart te zien.</div>
</div>
<div class="handleiding-step">
    <span class="handleiding-step-num">2</span>
    <div>Klik op een kenteken om in te zoomen. Offline voertuigen zijn grijs; u kunt ze (met veiligheidscode) tijdelijk ontgrendelen of verbergen.</div>
</div>
<div class="handleiding-step">
    <span class="handleiding-step-num">3</span>
    <div>Onder <strong>Configuratie</strong> stelt u markerstijl, kleur per voertuig en de veiligheidscode in.</div>
</div>
