<p>
    Onder <strong>Bedrijven</strong> staan alle tenants. U maakt een bedrijf aan (wizard), wijzigt pakket en modules,
    en wisselt in de zijbalk tussen <strong>Alle tenants</strong> en één specifiek bedrijf.
    Zonder geselecteerde tenant werkt u op platformniveau; mét tenant ziet u de admin zoals die klant die ziet.
</p>

