<div class="handleiding-step">
    <span class="handleiding-step-num">1</span>
    <div>Open <strong>Bedrijven</strong> om een tenant te zoeken, te bewerken of de onboarding-wizard te starten.</div>
</div>
<div class="handleiding-step">
    <span class="handleiding-step-num">2</span>
    <div>Stel het pakket in en vink aanvullende modules aan (GPS-trackers, extra contractklanten, Vloot). Dat is leidend voor het menu van de tenant én voor Tenant-abonnementen en de maandfactuur.</div>
</div>
<div class="handleiding-step">
    <span class="handleiding-step-num">3</span>
    <div>Kies in de zijbalk een tenant om ritten, website en instellingen in hun context te beheren. Kies <strong>Alle tenants</strong> terug voor platformschermen zoals NEXA facturatie en NEXA Suite ritten.</div>
</div>

<div class="handleiding-tip">
    <strong class="text-foreground">Centrale boekingen:</strong> ritten vanaf nexasuite.nl/boek gaan naar het dichtstbijzijnde actieve taxibedrijf.
    De tenant ziet ze in Ritten en in de chauffeur-app met het label NEXA Suite.
</div>
