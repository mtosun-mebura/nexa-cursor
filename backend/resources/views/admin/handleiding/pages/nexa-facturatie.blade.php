<p>
    <strong>NEXA facturatie</strong> is de SaaS-facturatie naar tenants: maandelijkse abonnementsfacturen,
    extra modules (GPS, extra contractklanten, Vloot) en handmatige factuurregels.
    Dit is iets anders dan ritfacturen van een taxibedrijf, en anders dan de provisie op NEXA Suite-ritten.
</p>

